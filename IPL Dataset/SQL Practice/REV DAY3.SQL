-- TOTAL RUNS SCORED IN EACH SEASON--
select m.season, 
sum(d.total_runs) as runs
from matches m
join deliveries d 
on m.id = d.match_id
group by m.season 
order by m.season



-- TOTAL MATCHES PLAYED IN EACH SEASON--

SELECT SEASON , COUNT(*) AS MATCHES
FROM MATCHES 
GROUP BY SEASON
ORDER BY SEASON



-- TOTAL RUNS EACH SEASON / EACH TEAM--

SELECT M.SEASON , D.BATTING_TEAM,
SUM(D.TOTAL_RUNS)F AS RUNS
FROM MATCHES M
JOIN DELIVERIES D
ON M.ID = D.MATCH_ID
GROUP BY M.SEASON , D.BATTING_TEAM
ORDER BY M.SEASON , RUNS DESC;



-- TOTAL WICKET IN EACH SEASON--

SELECT M.SEASON , D.BOWLER, COUNT(*) AS WICKETS
FROM MATCHES M
JOIN DELIVERIES D ON M.ID = D.MATCH_ID
WHERE D.PLAYER_DISMISSED IS NOT NULL
AND D.DISMISSAL_KIND NOT IN ('RUN OUT','RETIRED HURT')
GROUP BY M.SEASON , D.BOWLER
ORDER BY M.SEASON , WICKETS DESC;



-- TOP 5 RUN SCORER PER SEASON --

SELECT M.SEASON , D.BATSMAN , 
SUM(D.BATSMAN_RUNS) AS RUNS
FROM MATCHES M
JOIN DELIVERIES D
ON M.ID = D.MATCH_ID
GROUP BY M.SEASON , D.BATSMAN
ORDER BY M.SEASON , RUNS DESC


-- MATCHES WON PER SEASON--

SELECT SEASON , WINNER AS TEAM ,
COUNT(*) AS WINS
FROM MATCHES WHERE WINNER IS NOT NULL
GROUP BY SEASON , WINNER
ORDER BY SEASON , WINS DESC


-- HIGHEST TEAM SCORE IN EACH SEASON--

SELECT M.SEASON , D.BATTING_TEAM ,
SUM(D.TOTAL_RUNS) AS RUNS
FROM MATCHES M
JOIN DELIVERIES D
ON M.ID = D.MATCH_ID
GROUP BY M.SEASON , M.ID ,D.BATTING_TEAM
ORDER BY M.SEASON , RUNS DESC;



-- WHERE TEAM SCORED 200  EACH SEASON ---

SELECT M.SEASON , D.BATTING_TEAM , D.MATCH_ID ,
SUM(D.TOTAL_RUNS ) AS RUNS
FROM MATCHES M JOIN DELIVERIES D
ON M.ID = D.MATCH_ID 
GROUP BY M.SEASON ,  D.BATTING_TEAM ,D.MATCH_ID 
HAVING SUM(D.TOTAL_RUNS)>199
ORDER BY M.SEASON ,D.BATTING_TEAM, RUNS DESC





